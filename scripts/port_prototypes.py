"""Port the two LOCKED prototypes into the Next.js app.

- Scopes each prototype's CSS under a root class (.lp landing, .pf portfolio) so the routes can't leak styles.
- Prefixes @keyframes names so identical names in the two files can't collide.
- Swaps Google-Fonts family names for next/font CSS variables.
- Extracts static markup into TS modules (JSON-encoded strings) for server rendering.

Re-run after editing a prototype:  python scripts/port_prototypes.py
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT_MAP = {
    "'Geist Mono'": "var(--font-geist-mono)",
    "'Geist'": "var(--font-geist)",
    "'Anek Latin'": "var(--font-anek)",
    "'Anek Tamil'": "var(--font-anek-tamil)",
}


def split_top(s, sep=','):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    out.append(cur)
    return [x.strip() for x in out if x.strip()]


def scope_selector(sel, root):
    sel = sel.strip()
    if sel in (':root', 'html', 'body') or sel.startswith(':root'):
        return [root]
    if sel == '*':
        return [f'{root}', f'{root} *']
    if sel.startswith('*::') or sel.startswith('::'):
        return [f'{root} {sel}']
    return [f'{root} {sel}']


def parse_blocks(css):
    """Yield (prelude, body) for top-level blocks; body is raw text between the braces."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            break
        prelude = css[i:j].strip()
        depth, k = 1, j + 1
        while k < n and depth:
            if css[k] == '{':
                depth += 1
            elif css[k] == '}':
                depth -= 1
            k += 1
        yield prelude, css[j + 1:k - 1]
        i = k


def scope_css(css, root, kf_prefix):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    names = set(re.findall(r'@keyframes\s+([\w-]+)', css))
    out = []

    def rules(text):
        res = []
        for prelude, body in parse_blocks(text):
            if prelude.startswith('@media') or prelude.startswith('@supports'):
                res.append(f'{prelude}{{{"".join(rules(body))}}}')
            elif prelude.startswith('@keyframes'):
                name = prelude.split()[1]
                res.append(f'@keyframes {kf_prefix}{name}{{{body}}}')
            elif prelude.startswith('@property') or prelude.startswith('@font-face'):
                res.append(f'{prelude}{{{body}}}')
            else:
                sels = []
                for s in split_top(prelude):
                    sels.extend(scope_selector(s, root))
                # de-duplicate while keeping order
                seen, uniq = set(), []
                for s in sels:
                    if s not in seen:
                        seen.add(s); uniq.append(s)
                res.append(f'{",".join(uniq)}{{{body}}}')
        return res

    out = '\n'.join(rules(css))
    for name in names:
        out = re.sub(rf'(animation(?:-name)?\s*:\s*[^;{{}}]*?)\b{re.escape(name)}\b', rf'\g<1>{kf_prefix}{name}', out)
    for k, v in FONT_MAP.items():
        out = out.replace(k, v)
    return out


def extract(path):
    html = (ROOT / path).read_text(encoding='utf-8')
    style = re.search(r'<style>(.*?)</style>', html, re.S).group(1)
    after_style = html.split('</style>', 1)[1]
    markup = re.split(r"<script", after_style, maxsplit=1)[0].strip()
    ld = re.search(r'<script type="application/ld\+json">(.*?)</script>', html, re.S)
    script = re.findall(r'<script>(.*?)</script>', html, re.S)[-1]
    return style, markup, (ld.group(1).strip() if ld else None), script


def write(rel, text):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', rel, len(text), 'chars')


HEADER = '// GENERATED by scripts/port_prototypes.py from a LOCKED prototype. Edit the prototype, then re-run the script.\n'

# ---------- landing (prototype/landing-v02.html) ----------
style, markup, ld, _ = extract('prototype/landing-v02.html')
write('app/landing.css', '/* GENERATED from prototype/landing-v02.html (locked) · scoped to .lp */\n' + scope_css(style, '.lp', 'lp-'))
PORTFOLIO_ART = 'https://claude.ai/artifact/HMPJkuYxGdeJu3R7C16TCb'
markup = markup.replace(f'href="{PORTFOLIO_ART}" target="_blank" rel="noopener"', 'href="/portfolio"')
markup = markup.replace('Landing prototype v0.2', 'abishek.wiozen.in')
# WhatsApp links work without JavaScript
WA = '919345161419'
def wa_href(m):
    from urllib.parse import quote
    text = m.group(2)
    return f'href="https://wa.me/{WA}?text={quote(text)}" target="_blank" rel="noopener" data-wa="{text}"'
markup = re.sub(r'href="(#)" data-wa="([^"]*)"', wa_href, markup)
write('lib/landing/markup.ts', HEADER + 'export const LANDING_HTML: string = ' + json.dumps(markup, ensure_ascii=False) + ';\n')
write('lib/landing/jsonld.ts', HEADER + 'export const LANDING_JSONLD: string = ' + json.dumps(json.dumps(json.loads(ld), ensure_ascii=False), ensure_ascii=False) + ';\n')

# ---------- portfolio (prototype/v05-repo.html) ----------
style, markup, _, _ = extract('prototype/v05-repo.html')
write('app/portfolio/portfolio.css', '/* GENERATED from prototype/v05-repo.html (locked) · scoped to .pf */\n' + scope_css(style, '.pf', 'pf-'))
write('lib/portfolio/shell.ts', HEADER + 'export const PORTFOLIO_SHELL: string = ' + json.dumps(markup, ensure_ascii=False) + ';\n')
